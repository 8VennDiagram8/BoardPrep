/**
 * Generates supabase/seed.sql from the bundled TypeScript demo catalog.
 * Run with: npm run seed:generate
 * Requires Node 22.6+ (native TypeScript type stripping).
 */
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import {
  programs,
  subjects,
  topics,
  questions,
  flashcards,
} from '../src/data/seed.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function sql(value) {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  if (Array.isArray(value) || typeof value === 'object') {
    return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`
  }
  return `'${String(value).replace(/'/g, "''")}'`
}

function insert(table, columns, rows) {
  if (rows.length === 0) return ''
  const columnList = columns.join(', ')
  const values = rows.map((row) => `  (${columns.map((column) => sql(row[column])).join(', ')})`)
  return `insert into public.${table} (${columnList}) values\n${values.join(',\n')}\non conflict (id) do nothing;\n\n`
}

const statements = [
  '-- Generated by scripts/generate-seed.mjs — do not edit by hand.\n\n',
  insert('programs', ['id', 'code', 'name', 'short_name', 'description', 'accent', 'glyph'],
    programs.map((p) => ({
      id: p.id, code: p.code, name: p.name, short_name: p.shortName,
      description: p.description, accent: p.accent, glyph: p.glyph,
    }))),
  insert('subjects', ['id', 'program_id', 'name', 'code', 'description', 'glyph'],
    subjects.map((s) => ({ ...s, program_id: s.programId }))),
  insert('topics', ['id', 'subject_id', 'program_id', 'name', 'description'],
    topics.map((t) => ({ ...t, subject_id: t.subjectId, program_id: t.programId }))),
  insert('questions', ['id', 'program_id', 'subject_id', 'topic_id', 'prompt', 'options', 'answer_index', 'explanation', 'difficulty'],
    questions.map((q) => ({
      ...q,
      program_id: q.programId,
      subject_id: q.subjectId,
      topic_id: q.topicId,
      answer_index: q.answerIndex,
    }))),
  insert('flashcards', ['id', 'program_id', 'subject_id', 'topic_id', 'front', 'back'],
    flashcards.map((f) => ({
      ...f,
      program_id: f.programId,
      subject_id: f.subjectId,
      topic_id: f.topicId,
    }))),
].join('')

await writeFile(resolve(root, 'supabase/seed.sql'), statements, 'utf8')
console.log(`Wrote supabase/seed.sql (${programs.length} programs, ${subjects.length} subjects, ${topics.length} topics, ${questions.length} questions, ${flashcards.length} flashcards).`)
